"""vmlib.py: the two virtual machines of the vm suite (variants A and B).

A variant fixes: the opcode numbering (2-4 byte values per handler; every other byte value
dispatches to an invalid-opcode handler), the order of the handlers in the interpreter
source, the bytecode encryption (a rolling 8-bit key for opcode and operand bytes, a
rolling 64-bit key for 8-byte immediates, both re-derived from the block offset at every
jump target), the bit layout of the virtual flags, the condition codes of JCC, the MBA
forms inside the arithmetic handlers, the direction of the virtual stack and the order in
which the VM entry pushes the native arguments. The Python functions mirror the C text
exactly (enc_* inverts dec_*); emulate() in vmprog.py runs the encrypted bytecode with them.
"""
import random

M64 = (1 << 64) - 1
NL = chr(10)
HANDLERS = ('PUSH_IMM', 'PUSH_VREG', 'POP_VREG', 'ADD', 'NOR', 'NAND', 'SHL', 'SHR', 'MUL',
            'CMP', 'JCC', 'JMP', 'RET')
OPERAND = {'PUSH_IMM': 'imm', 'PUSH_VREG': 'reg', 'POP_VREG': 'reg', 'JCC': 'cc', 'RET': 'reg'}
CONDS = ('eq', 'ne', 'ult', 'ule', 'ugt', 'uge', 'slt')
# each condition from the four virtual flags (C expression, Python function)
COND_C = {'eq': 'zf', 'ne': '(zf ^ 1)', 'ult': 'cf', 'ule': '(cf | zf)', 'ugt': '((cf | zf) ^ 1)',
          'uge': '(cf ^ 1)', 'slt': '(sf ^ of)'}
COND_PY = {'eq': lambda cf, zf, sf, of: zf, 'ne': lambda cf, zf, sf, of: zf ^ 1,
           'ult': lambda cf, zf, sf, of: cf, 'ule': lambda cf, zf, sf, of: cf | zf,
           'ugt': lambda cf, zf, sf, of: (cf | zf) ^ 1, 'uge': lambda cf, zf, sf, of: cf ^ 1,
           'slt': lambda cf, zf, sf, of: sf ^ of}
VSTK = 64                       # virtual stack slots (u64) on the native stack


def rol8(v, n):
    v &= 0xff
    return ((v << n) | (v >> (8 - n))) & 0xff


def ror8(v, n):
    return rol8(v, 8 - n)


def rol64(v, n):
    v &= M64
    return ((v << n) | (v >> (64 - n))) & M64


def ror64(v, n):
    return rol64(v, 64 - n)


def sub_flags(a, b):
    """(cf, zf, sf, of) of the x86 SUB a - b."""
    r = (a - b) & M64
    return int(a < b), int(r == 0), r >> 63, ((a ^ b) & (a ^ r)) >> 63


class Variant:
    """Common part; VariantA / VariantB fill in the crypto, the flags and the C text."""
    letter = prefix = None
    up = True                   # virtual stack grows up (A) or down (B)
    push_order = ('x', 'y', 'z', 'w')
    flag_bits = {}              # cf / zf / sf / of -> bit of the virtual flags register
    seed = 0

    def __init__(self):
        r = random.Random(f'vm-variant-{self.letter}-{self.seed}')
        vals = list(range(256))
        r.shuffle(vals)
        self.ops = {}
        for h in HANDLERS:
            self.ops[h] = sorted(vals.pop() for _ in range(r.randint(2, 4)))
        self.handler_at = {v: h for h, vs in self.ops.items() for v in vs}
        bits = list(range(8))
        r.shuffle(bits)
        self.cc_bit = dict(zip(CONDS, bits))            # JCC operand: bit of the m word
        self.order = list(HANDLERS) + ['INVALID']
        r.shuffle(self.order)                           # handler order in the source

    def handler_of(self, op):
        return self.handler_at.get(op, 'INVALID')

    def cond_of_bit(self, bit):
        for c, b in self.cc_bit.items():
            if b == bit:
                return c
        return None

    def args_pushed(self, nargs):
        """Native arguments in the order the VM entry pushes them."""
        return [a for a in self.push_order if a in ('x', 'y', 'z', 'w')[:nargs]]

    def jcc_targets_pushed(self, t_true, t_false):
        """The two PUSH_IMM targets before a JCC, in push order, so that the handler's
        vsp[idx] (idx 1 when the condition holds) is t_true."""
        return [t_false, t_true] if self.up else [t_true, t_false]

    # ---------------------------------------------------------------- C text
    def c_flags(self):
        b = self.flag_bits
        return ' | '.join(f'({f} << {b[f]})' for f in ('cf', 'zf', 'sf', 'of'))

    def c_extract(self):
        b = self.flag_bits
        return ', '.join(f'{f} = (F >> {b[f]}) & 1' for f in ('cf', 'zf', 'sf', 'of'))

    def c_m(self):
        return ' | '.join(f'({COND_C[c]} << {self.cc_bit[c]})' for c in CONDS)

    def c_inc(self):
        """The interpreter body (vm_<letter>.inc), included inside every export of the
        variant after the VM entry pushed the native arguments."""
        P = self.letter
        tbl = []
        for v in range(256):
            h = self.handler_of(v)
            tbl.append('0' if h == 'INVALID' else f'&&h_{h.lower()} - &&h_invalid')
        rows = [', '.join(tbl[i:i + 4]) for i in range(0, 256, 4)]
        hs = self.handlers_c()
        out = [f'/* vm_{P.lower()}.inc: interpreter of VM variant {P} (generated by gen_vm.py).',
               '   Included in the body of every export of the variant, after the VM entry pushed',
               '   the native arguments onto the virtual stack: needs u64 vstk[VSTK], u64 *vsp and',
               '   VM_CODE (the encrypted bytecode, in .rdata). */',
               '    u64 R[16];                          /* virtual registers */',
               '    u64 F = 0;                          /* virtual flags */',
               '    const u8 *base = VM_CODE;',
               '    BAR(base);                          /* bytecode contents unknown to clang */',
               '    const u8 *vip = base;               /* virtual instruction pointer */',
               '    u8 k8; u64 k64;                     /* rolling keys */',
               f'    {P}_REKEY(0);',
               '    static const int OFF[256] = {      /* handler offsets from h_invalid */']
        out += ['        ' + r + ',' for r in rows]
        out += ['    };',
                '    const char *hb = (const char *)&&h_invalid;',
                f'    {P}_NEXT();']
        for h in self.order:
            out.append(f'h_{h.lower()}:')
            out += ['    ' + line for line in hs[h].strip().splitlines()]
        return NL.join(out) + NL


class VariantA(Variant):
    letter, prefix, seed = 'A', 'vma', 11
    up = True
    push_order = ('x', 'y', 'z', 'w')
    flag_bits = {'cf': 0, 'zf': 6, 'sf': 7, 'of': 11}

    def dec_op(self, b, k8):
        op = rol8(b ^ k8, 3)
        return op, (rol8(k8 ^ op, 3) + 0x5a) & 0xff

    def enc_op(self, op, k8):
        return ror8(op, 3) ^ k8, (rol8(k8 ^ op, 3) + 0x5a) & 0xff

    def dec_arg(self, b, k8):
        r = ((b ^ k8) - 0x2d) & 0xff
        return r, rol8((k8 + r) & 0xff, 5) ^ 0x93

    def enc_arg(self, r, k8):
        return ((r + 0x2d) & 0xff) ^ k8, rol8((k8 + r) & 0xff, 5) ^ 0x93

    def dec_imm(self, e, k64):
        v = e ^ k64
        return v, (rol64(k64 ^ v, 13) + 0x9e3779b97f4a7c15) & M64

    def enc_imm(self, v, k64):
        return v ^ k64, (rol64(k64 ^ v, 13) + 0x9e3779b97f4a7c15) & M64

    def block_keys(self, t):
        return (t * 0x6b + 0x1f) & 0xff, ((t * 0x9e3779b97f4a7c15) & M64) ^ 0xc2b2ae3d27d4eb4f

    def c_macros(self):
        return '''/* ---- variant A: stack grows up; op = rol8(b ^ k8, 3) ---- */
#define A_NEXT() do { u8 o_ = ROL8(*vip ^ k8, 3); vip++; k8 = (u8)(ROL8(k8 ^ o_, 3) + 0x5a); goto *(void *)(hb + OFF[o_]); } while (0)
#define A_ARG(r) do { r = (u8)((*vip ^ k8) - 0x2d); vip++; k8 = (u8)(ROL8((u8)(k8 + r), 5) ^ 0x93); } while (0)
#define A_IMM(v) do { v = *(const u64u *)vip ^ k64; vip += 8; k64 = ROL64(k64 ^ v, 13) + 0x9e3779b97f4a7c15ull; } while (0)
#define A_REKEY(t) do { k8 = (u8)((t) * 0x6b + 0x1f); k64 = ((u64)(t) * 0x9e3779b97f4a7c15ull) ^ 0xc2b2ae3d27d4eb4full; } while (0)
#define A_PUSH(v) (*vsp++ = (v))
#define A_POP() (*--vsp)
#define A_TOP (vsp[-1])
'''

    def handlers_c(self):
        return {
            'PUSH_IMM': '{ u64 v; A_IMM(v); A_PUSH(v); A_NEXT(); }',
            'PUSH_VREG': '{ u8 r; A_ARG(r); A_PUSH(R[r & 15]); A_NEXT(); }',
            'POP_VREG': '{ u8 r; A_ARG(r); R[r & 15] = A_POP(); A_NEXT(); }',
            'ADD': '''{ u64 b = A_POP(), a = A_TOP;         /* a + b = (a ^ b) + 2 (a & b) */
  u64 t1 = a ^ b; BAR(t1); u64 t2 = a & b; BAR(t2);
  A_TOP = t1 + 2 * t2; A_NEXT(); }''',
            'NOR': '''{ u64 b = A_POP(), a = A_TOP;         /* ~(a | b) = (a & b) - (a + b) - 1 */
  u64 t1 = a & b; BAR(t1); u64 t2 = a + b; BAR(t2);
  A_TOP = t1 - t2 - 1; A_NEXT(); }''',
            'NAND': '''{ u64 b = A_POP(), a = A_TOP;         /* ~(a & b) = (a | b) - (a + b) - 1 */
  u64 t1 = a | b; BAR(t1); u64 t2 = a + b; BAR(t2);
  A_TOP = t1 - t2 - 1; A_NEXT(); }''',
            'SHL': '{ u64 b = A_POP(), a = A_TOP; A_TOP = a << (b & 63); A_NEXT(); }',
            'SHR': '{ u64 b = A_POP(), a = A_TOP; A_TOP = a >> (b & 63); A_NEXT(); }',
            'MUL': '''{ u64 b = A_POP(), a = A_TOP;         /* a b = (a & b)(a | b) + (a & ~b)(~a & b) */
  u64 t1 = a & b; BAR(t1); u64 t2 = a | b; BAR(t2);
  u64 t3 = a & ~b; BAR(t3); u64 t4 = ~a & b; BAR(t4);
  A_TOP = t1 * t2 + t3 * t4; A_NEXT(); }''',
            'CMP': f'''{{ u64 b = A_POP(), a = A_POP();        /* flags of the x86 SUB a - b */
  u64 t1 = a ^ b; BAR(t1); u64 t2 = ~a & b; BAR(t2);
  u64 r = t1 - 2 * t2; BAR(r);              /* a - b = (a ^ b) - 2 (~a & b) */
  u64 nz = r | (0 - r); BAR(nz);
  u64 cf = (t2 | (~t1 & r)) >> 63, zf = (nz >> 63) ^ 1, sf = r >> 63, of = (t1 & (a ^ r)) >> 63;
  F = {self.c_flags()}; A_NEXT(); }}''',
            'JCC': f'''{{ u8 c; A_ARG(c);                      /* both targets are on the stack */
  u64 {self.c_extract()};
  u64 m = {self.c_m()};
  u64 idx = (m >> (c & 7)) & 1;             /* no native branch on the flags */
  vsp -= 2; u64 t = vsp[idx];               /* selected target -> new VIP */
  vip = base + t; A_REKEY(t); A_NEXT(); }}''',
            'JMP': '{ u64 t = A_POP(); vip = base + t; A_REKEY(t); A_NEXT(); }',
            'RET': '{ u8 r; A_ARG(r); return R[r & 15]; }',
            'INVALID': 'return 0xbadc0de0badc0deaull;',
        }


class VariantB(Variant):
    letter, prefix, seed = 'B', 'vmb', 30
    up = False
    push_order = ('y', 'w', 'x', 'z')
    flag_bits = {'cf': 9, 'zf': 2, 'sf': 30, 'of': 13}

    def dec_op(self, b, k8):
        op = ((b - k8) & 0xff) ^ 0xc3
        return op, ror8((k8 + op) & 0xff, 2) ^ 0x6d

    def enc_op(self, op, k8):
        return ((op ^ 0xc3) + k8) & 0xff, ror8((k8 + op) & 0xff, 2) ^ 0x6d

    def dec_arg(self, b, k8):
        r = (ror8(b, 1) + k8) & 0xff
        return r, (((k8 ^ r) * 0x1d) + 0x41) & 0xff

    def enc_arg(self, r, k8):
        return rol8((r - k8) & 0xff, 1), (((k8 ^ r) * 0x1d) + 0x41) & 0xff

    def dec_imm(self, e, k64):
        v = (ror64(e, 7) - k64) & M64
        return v, ((k64 ^ v) * 0x2545f4914f6cdd1d + 0x632be59bd9b4e019) & M64

    def enc_imm(self, v, k64):
        return rol64((v + k64) & M64, 7), ((k64 ^ v) * 0x2545f4914f6cdd1d + 0x632be59bd9b4e019) & M64

    def block_keys(self, t):
        k64 = (rol64((t + 0x632be59bd9b4e019) & M64, 29) * 0xff51afd7ed558ccd) & M64
        return ((t ^ 0x3c) * 0x25) & 0xff, k64

    def c_macros(self):
        return '''/* ---- variant B: stack grows down; op = (b - k8) ^ 0xc3 ---- */
#define B_NEXT() do { u8 o_ = (u8)((u8)(*vip - k8) ^ 0xc3); vip++; k8 = (u8)(ROR8((u8)(k8 + o_), 2) ^ 0x6d); goto *(void *)(hb + OFF[o_]); } while (0)
#define B_ARG(r) do { r = (u8)(ROR8(*vip, 1) + k8); vip++; k8 = (u8)((u8)(k8 ^ r) * 0x1d + 0x41); } while (0)
#define B_IMM(v) do { v = ROR64(*(const u64u *)vip, 7) - k64; vip += 8; k64 = (k64 ^ v) * 0x2545f4914f6cdd1dull + 0x632be59bd9b4e019ull; } while (0)
#define B_REKEY(t) do { k8 = (u8)(((t) ^ 0x3c) * 0x25); k64 = ROL64((u64)(t) + 0x632be59bd9b4e019ull, 29) * 0xff51afd7ed558ccdull; } while (0)
#define B_PUSH(v) (*--vsp = (v))
#define B_POP() (*vsp++)
#define B_TOP (vsp[0])
'''

    def handlers_c(self):
        return {
            'PUSH_IMM': '{ u64 v; B_IMM(v); B_PUSH(v); B_NEXT(); }',
            'PUSH_VREG': '{ u8 r; B_ARG(r); B_PUSH(R[r & 15]); B_NEXT(); }',
            'POP_VREG': '{ u8 r; B_ARG(r); R[r & 15] = B_POP(); B_NEXT(); }',
            'ADD': '''{ u64 b = B_POP(), a = B_TOP;         /* a + b = (a | b) + (a & b) */
  u64 t1 = a | b; BAR(t1); u64 t2 = a & b; BAR(t2);
  B_TOP = t1 + t2; B_NEXT(); }''',
            'NOR': '''{ u64 b = B_POP(), a = B_TOP;         /* ~(a | b) = ~a - (~a & b) */
  u64 t1 = ~a; BAR(t1); u64 t2 = t1 & b; BAR(t2);
  B_TOP = t1 - t2; B_NEXT(); }''',
            'NAND': '''{ u64 b = B_POP(), a = B_TOP;         /* ~(a & b) = (a ^ b) + ~(a | b) */
  u64 t1 = a ^ b; BAR(t1); u64 t2 = ~(a | b); BAR(t2);
  B_TOP = t1 + t2; B_NEXT(); }''',
            'SHL': '{ u64 b = B_POP(), a = B_TOP; B_TOP = a << (b & 63); B_NEXT(); }',
            'SHR': '{ u64 b = B_POP(), a = B_TOP; B_TOP = a >> (b & 63); B_NEXT(); }',
            'MUL': '''{ u64 b = B_POP(), a = B_TOP;         /* a b = (a | b)(a & b) + (a & ~b)(b & ~a) */
  u64 t1 = a | b; BAR(t1); u64 t2 = a & b; BAR(t2);
  u64 t3 = b & ~a; BAR(t3); u64 t4 = a & ~b; BAR(t4);
  B_TOP = t1 * t2 + t4 * t3; B_NEXT(); }''',
            'CMP': f'''{{ u64 b = B_POP(), a = B_POP();        /* flags of the x86 SUB a - b */
  u64 t1 = a & ~b; BAR(t1); u64 t2 = ~a & b; BAR(t2);
  u64 r = t1 - t2; BAR(r);                  /* a - b = (a & ~b) - (~a & b) */
  u64 d = a ^ b; BAR(d); u64 nz = r | (0 - r); BAR(nz);
  u64 cf = (t2 | (~d & r)) >> 63, zf = (nz >> 63) ^ 1, sf = r >> 63, of = (d & (a ^ r)) >> 63;
  F = {self.c_flags()}; B_NEXT(); }}''',
            'JCC': f'''{{ u8 c; B_ARG(c);                      /* both targets are on the stack */
  u64 {self.c_extract()};
  u64 m = {self.c_m()};
  u64 idx = (m >> (c & 7)) & 1;             /* no native branch on the flags */
  u64 t = vsp[idx]; vsp += 2;               /* selected target -> new VIP */
  vip = base + t; B_REKEY(t); B_NEXT(); }}''',
            'JMP': '{ u64 t = B_POP(); vip = base + t; B_REKEY(t); B_NEXT(); }',
            'RET': '{ u8 r; B_ARG(r); return R[r & 15]; }',
            'INVALID': 'return 0xbadc0de0badc0debull;',
        }


VARIANTS = {'A': VariantA(), 'B': VariantB()}
